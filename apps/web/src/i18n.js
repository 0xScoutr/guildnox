function readStoredLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS.some((item) => item.id === saved)) return saved;
  } catch { /* ignore */ }
  const nav = (typeof navigator !== "undefined" && navigator.language || "pt").slice(0, 2).toLowerCase();
  if (nav === "es") return "es";
  if (nav === "en") return "en";
  return "pt";
}

let currentLang = readStoredLang();

export function getLang() {
  return currentLang;
}

export function setLang(id) {
  if (!LANGS.some((item) => item.id === id)) return currentLang;
  currentLang = id;
  try { localStorage.setItem(STORAGE_KEY, id); } catch { /* ignore */ }
  if (typeof document !== "undefined") document.documentElement.lang = id;
  return currentLang;
}

export function t(key, vars = {}) {
  const table = dict[currentLang] || dict.pt;
  let text = table[key] ?? dict.pt[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ""));
  }
  return text;
}

if (typeof document !== "undefined") {
  document.documentElement.lang = currentLang;
}
